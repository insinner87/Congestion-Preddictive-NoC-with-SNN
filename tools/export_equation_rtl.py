#!/usr/bin/env python3
"""Export the distilled fixed-point equation constants to a SystemVerilog package."""

from __future__ import annotations

import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def signed_literal(value: int, width: int) -> str:
    encoded = value & ((1 << width) - 1)
    return f"{width}'sh{encoded:0{(width + 3) // 4}x}"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--equation", type=Path, default=ROOT / "models/distilled_equation.json")
    parser.add_argument("--output", type=Path, default=ROOT / "rtl/congestion/distilled_congestion_model_pkg.sv")
    parser.add_argument("--version", type=int, default=1)
    args = parser.parse_args()
    model = json.loads(args.equation.read_text(encoding="utf-8"))
    coefficients = [int(value) for value in model["coefficient_signed_8"]]
    if len(coefficients) != 7 or any(not -128 <= value <= 127 for value in coefficients):
        parser.error("the equation requires seven signed 8-bit coefficients")
    bias = int(model["bias_signed_12"])
    threshold = int(model["decision_threshold"])
    if not -2048 <= bias <= 2047 or not -2048 <= threshold <= 2047:
        parser.error("bias and threshold must fit signed 12-bit values")
    packed = "{" + ", ".join(signed_literal(value, 8) for value in reversed(coefficients)) + "}"
    source = "\n".join([
        "// Generated by tools/export_equation_rtl.py from the trained SNN distillation.",
        "package distilled_congestion_model_pkg;",
        f"    localparam int MODEL_VERSION = {args.version};",
        f"    localparam logic signed [55:0] EQUATION_COEFFICIENTS = {packed};",
        f"    localparam logic signed [11:0] EQUATION_BIAS = {signed_literal(bias, 12)};",
        f"    localparam logic signed [11:0] EQUATION_THRESHOLD = {signed_literal(threshold, 12)};",
        f"    localparam int FRACTIONAL_BITS = {int(model['fixed_point_scale']).bit_length() - 1};",
        "endpackage",
        "",
    ])
    args.output.write_text(source, encoding="utf-8")
    print(f"Exported distilled equation version {args.version} to {args.output}")


if __name__ == "__main__":
    main()
